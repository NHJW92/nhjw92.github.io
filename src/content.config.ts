import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';
import { TRAVEL_MODES } from './lib/travel';

const LANG = z.enum(['nl', 'en', 'de']);

/** Posts as written by Babet and Niels: the source of truth. */
const posts = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/posts' }),
  schema: z.object({
    title: z.string(),
    date: z.coerce.date(),
    // Language this post is written in. The other languages are translated by AI.
    lang: LANG.optional().nullable().transform((l) => l ?? 'nl'),
    location: z.string(),
    // Coordinates put the post on the route map. Optional, but recommended.
    lat: z.coerce.number().optional().nullable(),
    lng: z.coerce.number().optional().nullable(),
    // How you got here; styles the line leading to this stop on the map.
    travel: z.enum(TRAVEL_MODES).optional().nullable(),
    summary: z.string().optional().nullable(),
    cover: z.string().optional().nullable(),
    coverAlt: z.string().optional().nullable(),
    gallery: z
      .array(z.object({ image: z.string(), caption: z.string().optional().nullable() }))
      .optional()
      .nullable()
      .transform((g) => (g ?? []).filter((i) => i.image)),
    draft: z.boolean().optional().default(false),
  }),
});

/**
 * AI translations, generated by scripts/translate.mjs into
 * src/content/translations/<lang>/<post-id>.md. Only the text lives here;
 * dates, coordinates and photos always come from the source post.
 */
const translations = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/translations' }),
  schema: z.object({
    title: z.string(),
    location: z.string().optional().nullable(),
    summary: z.string().optional().nullable(),
    coverAlt: z.string().optional().nullable(),
    captions: z.array(z.string().nullable()).optional().nullable(),
    sourceLang: LANG,
    sourceHash: z.string(),
    translatedBy: z.string().optional().nullable(),
  }),
});

export const collections = { posts, translations };
